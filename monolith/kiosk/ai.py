"""AI pre-consultation summary for the doctor.

The summary is generated by OpenAI from de-identified data only: no name,
Patient ID, phone, address, ID document or date of birth ever leaves the
server. Free text the patient typed is scrubbed of their name, numbers that
look like phone or ID numbers, and e-mail addresses. The doctor reviews the
summary; it never diagnoses.
"""

import json
import logging
import re
import urllib.error
import urllib.request

from django.conf import settings
from django.utils import timezone

from .models import get_openai_api_key
from .views import latest_vitals

logger = logging.getLogger(__name__)

API_URL = "https://api.openai.com/v1/chat/completions"
TIMEOUT_SECONDS = 40
PREVIOUS_VISITS = 3

SYSTEM_PROMPT = """You are a clinical assistant in a primary-care clinic. Before the consultation, \
prepare a brief summary for the doctor from the de-identified data you are given.

Rules:
- Use only the data provided. Never invent findings, history or results.
- Do not diagnose and do not recommend specific drugs. You may list points the doctor may want to check.
- Point out anything that needs attention first, such as a very high blood pressure, an abnormal heart rate, \
or a drug allergy relevant to past prescriptions.
- Say plainly when information is missing (for example "allergy status unknown").
- English, at most 160 words, in this format with short bullet points:
Presenting complaint:
Vitals today:
Relevant history:
Allergies & recent medication:
Points to check:"""


class AIError(Exception):
    """The summary could not be generated; the message is safe to show to staff."""


_EMAIL = re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")
_LONG_NUMBER = re.compile(r"\+?\d[\d\s().-]{5,}\d")


def scrub(text, patient):
    """Remove what could identify the patient from free text."""
    text = _EMAIL.sub("[email]", text or "")
    text = _LONG_NUMBER.sub("[number]", text)
    for part in patient.name.split():
        if len(part) >= 3:
            text = re.sub(rf"\b{re.escape(part)}\b", "[name]", text, flags=re.IGNORECASE)
    return " ".join(text.split())


def summary_input(visit):
    """The de-identified facts sent to the model, as plain text."""
    patient = visit.patient
    lines = []
    if patient.age is not None:
        lines.append(f"Age: {patient.age}")
    lines.append(f"Reason for visit: {scrub(visit.reason, patient) or 'not given'}")

    vitals = latest_vitals(visit.measurements.order_by("-measured_at"))
    bp, weight = vitals["bp"], vitals["weight"]
    if bp:
        line = f"Blood pressure: {bp.systolic_bp}/{bp.diastolic_bp} mmHg ({vitals['bp_category'].label}, ACC/AHA)"
        if bp.heart_rate_bpm:
            line += f"; pulse {bp.heart_rate_bpm} bpm ({vitals['hr_status'].label.lower()})"
        lines.append(line)
    else:
        lines.append("Blood pressure: not measured")
    if weight:
        line = f"Weight: {weight.weight_kg:.1f} kg"
        if patient.height_cm:
            bmi = weight.weight_kg / (patient.height_cm / 100) ** 2
            line += f"; height {patient.height_cm:.0f} cm; BMI {bmi:.1f}"
        lines.append(line)
    else:
        lines.append("Weight: not measured")

    if patient.has_drug_allergy is None:
        lines.append("Drug allergy: unknown")
    elif patient.has_drug_allergy:
        lines.append(f"Drug allergy: yes, to {scrub(patient.drug_allergies, patient)}")
    else:
        lines.append("Drug allergy: none known")
    lines.append(f"Medical history: {scrub(patient.medical_history, patient) or 'not recorded'}")

    previous = (
        patient.visits.filter(status=visit.COMPLETED, created_at__lt=visit.created_at)
        .exclude(pk=visit.pk)
        .prefetch_related("prescriptions")
        .order_by("-created_at")[:PREVIOUS_VISITS]
    )
    today = timezone.localdate()
    for v in previous:
        days = (today - timezone.localtime(v.created_at).date()).days
        drugs = ", ".join(f"{p.drug} {p.dose} {p.frequency}".strip() for p in v.prescriptions.all())
        diagnosis = scrub(v.diagnosis, patient) or "no diagnosis recorded"
        code = f" ({v.diagnosis_code})" if v.diagnosis_code else ""
        lines.append(f"Previous visit {days} days ago: {diagnosis}{code}" + (f"; prescribed {drugs}" if drugs else ""))
    if not previous:
        lines.append("Previous visits: none recorded")
    return "\n".join(lines)


def generate_summary(visit):
    """Ask OpenAI for the summary. Returns (text, model). Raises AIError."""
    key = get_openai_api_key()
    if not key:
        raise AIError("No OpenAI API key is set. An administrator can add one under Admin › System settings.")
    payload = {
        "model": settings.OPENAI_MODEL,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": summary_input(visit)},
        ],
        "temperature": 0.2,
        "max_tokens": 400,
    }
    request = urllib.request.Request(
        API_URL,
        data=json.dumps(payload).encode(),
        headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=TIMEOUT_SECONDS) as response:
            data = json.load(response)
    except urllib.error.HTTPError as exc:
        logger.warning("OpenAI request failed: HTTP %s", exc.code)
        if exc.code == 401:
            raise AIError("The OpenAI API key was rejected. Check it under Admin › System settings.") from exc
        if exc.code == 429:
            raise AIError("OpenAI is busy or the account has run out of credit. Try again in a minute.") from exc
        raise AIError(f"OpenAI returned an error (HTTP {exc.code}). Try again later.") from exc
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        logger.warning("OpenAI request failed: %s", exc)
        raise AIError("Could not reach OpenAI. Check the server's internet connection and try again.") from exc
    except ValueError as exc:
        raise AIError("OpenAI sent an answer we could not read. Try again.") from exc
    try:
        text = data["choices"][0]["message"]["content"].strip()
    except (KeyError, IndexError, TypeError, AttributeError) as exc:
        raise AIError("OpenAI sent an empty answer. Try again.") from exc
    if not text:
        raise AIError("OpenAI sent an empty answer. Try again.")
    return text, data.get("model") or settings.OPENAI_MODEL
